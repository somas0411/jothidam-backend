ORDER = ('ta', 'hi', 'te', 'kn', 'ml', 'mr', 'bn')


def _rows(table):
    """{english: tuple} -> {lang: {english: text}}."""
    out = {lang: {} for lang in ORDER}
    for en, row in table.items():
        for lang, text in zip(ORDER, row):
            if text:
                out[lang][en] = text
    return out


