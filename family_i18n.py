def ordinal(n, lang):
    n = int(n)
    if lang == 'ta':
        return f'{n}-ம்'
    if lang in ('hi', 'mr'):
        return f'{n}वाँ' if lang == 'hi' else f'{n}वे'
    if lang == 'te':
        return f'{n}వ'
    if lang == 'kn':
        return f'{n}ನೇ'
    if lang == 'ml':
        return f'{n}-ാം'
    if lang == 'bn':
        return f'{n}-তম'
    return str(n)


