def _leaf(text, lang):
    if text in VOCAB[lang]:
        return VOCAB[lang][text]
    names = _names(lang)
    if text in names:
        return names[text]
    low = text[:1].upper() + text[1:]
    if low in VOCAB[lang]:
        return VOCAB[lang][low]
    return None


def tr(text, lang):
    """A family-engine value in the report language; unknown parts are kept as written."""
    if lang not in ORDER or not isinstance(text, str) or not re.search('[A-Za-z]', text):
        return text
    return _tr(text, lang)


@lru_cache(maxsize=20000)
def _tr(text, lang):
    s = text.strip()
    if not s:
        return text
    if not re.search('[A-Za-z]{2,}', s):
        return text
    hit = _leaf(s, lang)
    if hit is not None:
        return hit
    for rx, tpls in PATTERNS:
        m = rx.match(s)
        if not m:
            continue
        if rx.pattern == r'^(?P<o>\d+)(?:st|nd|rd|th)$':
            return ordinal(m.group('o'), lang)
        parts = {}
        for k, v in m.groupdict().items():
            if v is None:
                parts[k] = ''
            elif k.startswith('o'):
                parts[k] = ordinal(re.match(r'\d+', v).group(0), lang)
            elif k.startswith(('n', 'k', 'd')):
                parts[k] = v
            elif k == 'rest':
                parts[k] = (', ' + tr(v[2:], lang)) if v else ''
            else:
                parts[k] = tr(v, lang)
        return tpls[lang].format(**parts).replace('  ', ' ').strip()
    # a trailing parenthesis: "X (Y)"
    m = re.match(r'^(?P<a>.+) \((?P<b>[^()]+)\)$', s)
    if m:
        return f"{tr(m.group('a'), lang)} ({tr(m.group('b'), lang)})"
    for sep in SPLITS:
        parts = _split(s, sep)
        if len(parts) > 1:
            if sep == ': ':
                a, b = parts[0], sep.join(parts[1:])
                return f'{tr(a, lang)}: {tr(b, lang)}'
            joiner = WORD[lang]['and'] if sep == ' and ' else sep
            return joiner.join(tr(p, lang) for p in parts)
    return text


def _split(s, sep):
    """s split at sep, but not inside brackets."""
    parts, depth, start, i = [], 0, 0, 0
    while i < len(s):
        ch = s[i]
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        elif depth == 0 and s.startswith(sep, i):
            parts.append(s[start:i])
            i += len(sep)
            start = i
            continue
        i += 1
    parts.append(s[start:])
    return parts


