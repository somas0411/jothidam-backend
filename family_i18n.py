def rule_name(name, lang):
    return RULE_NAMES.get(lang, {}).get(name, name)


def rule_text(name, text, lang):
    """The rule text in the report language; English where no translation is held yet."""
    if lang != 'ta' or name not in RULE_TEXT_TA:
        return text
