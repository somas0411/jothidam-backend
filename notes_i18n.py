def active(lang, target='xlsx'):
    """True when the Notes text is translated for this language and output. Tamil is
    translated in the PDF and on the web page, not in Excel (golden test)."""
    return lang in NOTE_LANGS


def varga_rule(key, lang, en_rule, target='xlsx'):
    """The rule of a divisional chart in the report language (English for en and bi, and for ta in Excel)."""
    if not active(lang, target):
        return en_rule
    signs = {f'r{i}': i18n.rasi(i, lang) for i in range(12)}
    return T[lang][key].format(**signs)


def _mandi(m, v, t, lang):
    md = v.get('mandi')
    if not md:
        return t['mandi'] + t['mandi.none']
    fmt = '%d-%m-%Y %H:%M:%S'
    return t['mandi'] + t['mandi.chart'].format(
        daynight=t['day'] if md['is_day'] else t['night'], weekday=i18n.weekday(md['weekday'], lang),
        ghatis=md['ghatis'], from_=t['sunrise'] if md['is_day'] else t['sunset'],
        start=md['period_start'].strftime(fmt), rise=md['rise_time'].strftime(fmt))


def how_items(res, lang, target='xlsx'):
    """(label, text) rows of 'How this report was calculated' for a translated language."""
    t = T[lang]
    m, v, kp = res['meta'], res['vedic'], res['kp']
    fmt = '%d-%m-%Y %H:%M:%S'
    vim = t['vim'].format(days=m['year_days']) + (t['vim.pdf'] if target == 'pdf' else '')
    return [
        (t['k.ephemeris'], t['ephemeris'].format(engine=m['engine'])),
        (t['k.birth'], t['birth'].format(local=m['local_dt'].strftime(fmt), tz=m['tz'], off=m['utc_offset_str'],
                                         ut=m['ut_dt'].strftime(fmt), jd=m['jd_ut'])),
        (t['k.place'], t['place'].format(pob=m['pob'], lat=f"{m['lat']:.4f}", lon=f"{m['lon']:.4f}")),
        (t['k.vedic_ay'], t['vedic_ay'].format(name=m['ayanamsha_name'], dms=v['ayanamsha_dms'])),
        (t['k.kp_ay'], t['kp_ay'].format(dms=kp['ayanamsha_dms'], where=t[f'where.{target}'])),
        (t['k.nodes'], t['nodes'].format(node=t['node.true' if m['node'] == 'true' else 'node.mean'])),
        (t['k.vedic_houses'], t['vedic_houses']),
        (t['k.kp_houses'], t['kp_houses'].format(system=kp['house_system'])),
        (t['k.kp_sig'], t['kp_sig']),
        (t['k.vim'], vim),
        (t['k.panchang'], t['panchang']),
        (t['k.mandi'], _mandi(m, v, t, lang)),
        (t['k.combust'], t['combust']),
        (t['k.dignity'], t['dignity']),
        (t['k.alp'], t['alp'].format(days=m['year_days'])),
        (t['k.generated'], m['generated_at'].strftime('%d-%m-%Y %H:%M') + f" ({m['utc_offset_str']})"),
    ]


def retro_line(lang):
    return T[lang]['retro'].format(mark=i18n.retro_mark(lang))


def roman_line(lang):
    return T[lang]['roman']
