def T(key, lang='en'):
    row = ROWS[key]
    if lang == 'bi':
        return row[0] if row[0] == row[1] else f'{row[0]} / {row[1]}'
    return row[LANGS.index(lang)] if lang in LANGS else row[0]


def _rupees(paise):
    return f'₹{paise // 100}' + (f'.{paise % 100:02d}' if paise % 100 else '')


def _ist(dt):
    from datetime import timedelta, timezone
    return dt.astimezone(timezone(timedelta(hours=5, minutes=30))).strftime('%d-%m-%Y %H:%M IST')


